// ── Combined context ──────────────────────────────────────────
interface AppPrefs {
  lang: Lang; setLang: (l: Lang) => void;
  server: GameServer; setServer: (s: GameServer) => void;
  servers: GameServer[]; toggleServer: (s: GameServer) => void;
}

const LangCtx = createContext<AppPrefs>({
  lang: "pt", setLang: () => {},
  server: "west", setServer: () => {},
  servers: ["west"], toggleServer: () => {},
});

const VALID_LANGS: readonly Lang[] = ["pt", "en", "es"];
const VALID_SERVERS: readonly GameServer[] = ["europe", "west", "east"];

// Lê lang/server validando contra o conjunto conhecido — sem isso, um valor
// velho/corrompido no localStorage (versão anterior do código, edição manual,
// sync entre navegadores) vira uma key inválida em S[lang][key] (useT) e
// derruba a árvore INTEIRA sem erro nenhum: LangProvider embrulha todo o
// <App/> em main.tsx, antes de qualquer ErrorBoundary existir — tela branca
// eterna, sem stack trace, sem console.error. Este era o bug do "site sempre
// fica em branco".
//
// Detecção de idioma (1ª visita, sem lang no localStorage):
//   navigator.language → "pt-BR", "en-US", "es-ES", "de-DE", etc.
//   Extrai o prefixo (pt/en/es), mapeia pro Lang suportado.
//   Se não for pt/en/es, cai em inglês (fallback universal).
function detectLang(): Lang {
  const nav = (typeof navigator !== "undefined" ? navigator.language : "") || "en";
  const prefix = nav.slice(0, 2).toLowerCase();
  if (prefix === "pt") return "pt";
  if (prefix === "es") return "es";
  return "en";
}

function readLang(): Lang {
  const v = localStorage.getItem("lang");
  if ((VALID_LANGS as readonly string[]).includes(v ?? "")) return v as Lang;
  // Sem preferência salva — detecta do navegador
  const detected = detectLang();
  localStorage.setItem("lang", detected);
  return detected;
}
function readServer(): GameServer {
  const v = localStorage.getItem("server");
  return (VALID_SERVERS as readonly string[]).includes(v ?? "") ? (v as GameServer) : "west";
}
function readServers(): GameServer[] {
  try {
    const stored = JSON.parse(localStorage.getItem("servers") ?? "null");
    if (Array.isArray(stored)) {
      const valid = stored.filter((s): s is GameServer => (VALID_SERVERS as readonly string[]).includes(s));
      if (valid.length > 0) return valid;
    }
  } catch { /**/ }
  return ["west"];
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState]       = useState<Lang>(readLang);
  const [server, setServerState]   = useState<GameServer>(readServer);
  const [servers, setServersState] = useState<GameServer[]>(readServers);

  function setLang(l: Lang) { localStorage.setItem("lang", l); setLangState(l); }

  function setServer(s: GameServer) { localStorage.setItem("server", s); setServerState(s); }

  function toggleServer(s: GameServer) {
    setServersState(prev => {
      const has = prev.includes(s);
      if (has && prev.length === 1) return prev; // can't deselect last
      const next = has ? prev.filter(x => x !== s) : [...prev, s];
      localStorage.setItem("servers", JSON.stringify(next));
      // if active was removed, switch to first remaining
      if (has && server === s) {
        localStorage.setItem("server", next[0]);
        setServerState(next[0]);
      }
      return next;
    });
  }

  return createElement(LangCtx.Provider, { value: { lang, setLang, server, setServer, servers, toggleServer } }, children);
}

export const useLang   = () => useContext(LangCtx);
export const useServer = () => { const { server, setServer, servers, toggleServer } = useContext(LangCtx); return { server, setServer, servers, toggleServer }; };

export function useT() {
  const { lang } = useLang();
  // Fallback pt → chave crua: uma chave faltando num idioma degrada pro
  // português em vez de renderizar "undefined" na tela.
  return (key: TKey): string => S[lang][key] ?? S.pt[key] ?? key;
}

// ── Item name resolution ──────────────────────────────────────
function tierDotEnchant(id: string): string {
  const tier    = id.match(/^T(\d+)_/)?.[1] ?? "";
  const enchant = id.match(/@(\d+)$/)?.[1] ?? "0";
  return `${tier}.${enchant}`;
}

function baseIdOf(id: string): string {
  return id.replace(/^T\d+_/, "").replace(/@\d+$/, "");
}

// ponytail: ES item names fall back to PT; populate es-items.json to add them
export function itemLocalName(item: AlbionItem, lang: Lang): string {
  // noTier (battlemounts): sem prefixo numérico em nenhum idioma.
  const prefix = item.noTier ? "" : tierDotEnchant(item.id);
  if (lang === "en" && item.nameEn) return `${prefix} ${item.nameEn}`.trim();
  if (lang === "es") {
    const base = (ES_ITEMS as Record<string, string>)[baseIdOf(item.id)];
    if (base) return `${prefix} ${base}`.trim();
  }
  return item.name;
}

