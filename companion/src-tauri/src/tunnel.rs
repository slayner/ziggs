/// Convert an IPv4 netmask to CIDR prefix length (e.g. 255.255.255.0 → 24).
fn mask_to_cidr(mask: &Ipv4Addr) -> u8 {
    let bits = u32::from(*mask);
    bits.count_ones() as u8
}

#[cfg(target_os = "windows")]
fn stale_route_cleanup_script() -> &'static str {
    // PowerShell is the only way to reliably remove routes by NextHop.
    // netsh can only delete by prefix, not by gateway. We keep this as
    // PowerShell but with SilentlyContinue to avoid errors on empty results.
    "Get-NetRoute -NextHop '10.99.0.1' -ErrorAction SilentlyContinue | Remove-NetRoute -Confirm:$false -ErrorAction SilentlyContinue"
}

#[cfg(target_os = "windows")]
pub fn scrub_stale_routes_now() -> Result<()> {
    // Use PowerShell for route cleanup — it's the only way to delete by
    // NextHop. CREATE_NO_WINDOW is applied; PowerShell may flash briefly
    // but this only runs on tunnel stop/start, not in a loop.
    let output = crate::winutil::no_window(std::process::Command::new("powershell"))
        .args([
            "-NoProfile",
            "-NonInteractive",
            "-Command",
            stale_route_cleanup_script(),
        ])
        .output()?;
    if !output.status.success() && !output.stderr.is_empty() {
        let err = String::from_utf8_lossy(&output.stderr);
        if !err.contains("No matching") && !err.is_empty() {
            return Err(anyhow!("Windows failed to remove old tunnel routes: {err}"));
        }
    }
    Ok(())
}

#[cfg(not(target_os = "windows"))]
pub fn scrub_stale_routes_now() -> Result<()> {
    Ok(())
}

#[cfg(target_os = "windows")]
#[derive(Clone, Debug)]
struct PathCandidate {
    if_index: u32,
    name: String,
    local_ip: Ipv4Addr,
    metric: u32,
    latency_ms: Option<f64>,
    available: bool,
}

#[cfg(target_os = "windows")]
fn resolve_endpoint(endpoint: &str) -> Result<SocketAddr> {
    endpoint
        .to_socket_addrs()
        .map_err(|e| anyhow!("invalid endpoint: {e}"))?
        .find(|addr| addr.is_ipv4())
        .ok_or_else(|| anyhow!("endpoint has no IPv4 address"))
}

/// List physical/virtual interfaces with IPv4, default gateway, and status Up.
/// The WireGuard handshake below confirms actual internet/VPS reachability.
#[cfg(target_os = "windows")]
fn enumerate_internet_paths() -> Result<Vec<PathCandidate>> {
    let script = r#"Get-NetIPConfiguration | Where-Object { $_.NetAdapter.Status -eq 'Up' -and $_.IPv4DefaultGateway -and $_.IPv4Address -and $_.InterfaceAlias -ne 'Ziggs' } | ForEach-Object { "{0}`t{1}`t{2}`t{3}" -f $_.InterfaceIndex,$_.InterfaceAlias,$_.IPv4Address[0].IPAddress,$_.NetIPv4Interface.InterfaceMetric }"#;
    let output = crate::winutil::no_window(std::process::Command::new("powershell"))
        .args(["-NoProfile", "-NonInteractive", "-Command", script])
        .output()
        .map_err(|e| anyhow!("failed to list connections: {e}"))?;
    if !output.status.success() {
        return Err(anyhow!("Windows failed to list internet connections"));
    }
    let mut paths = Vec::new();
    for line in String::from_utf8_lossy(&output.stdout).lines() {
        let mut cols = line.trim().split('\t');
        let (Some(idx), Some(name), Some(ip), Some(metric)) =
            (cols.next(), cols.next(), cols.next(), cols.next())
        else {
            continue;
        };
        let (Ok(if_index), Ok(local_ip), Ok(metric)) = (idx.parse(), ip.parse(), metric.parse())
        else {
            continue;
        };
        if paths.iter().any(|p: &PathCandidate| p.if_index == if_index) {
            continue;
        }
        paths.push(PathCandidate {
            if_index,
            name: name.to_string(),
            local_ip,
            metric,
            latency_ms: None,
            available: false,
        });
    }
    paths.sort_by_key(|p| p.metric);
    Ok(paths)
}

#[cfg(target_os = "windows")]
fn open_path_socket(path: &PathCandidate, endpoint: SocketAddr) -> Result<UdpSocket> {
    use std::os::windows::io::AsRawSocket;
    use windows_sys::Win32::Networking::WinSock::{
        setsockopt, IPPROTO_IP, IP_UNICAST_IF, SOCKET_ERROR,
    };

    let udp = UdpSocket::bind(SocketAddr::new(IpAddr::V4(path.local_ip), 0))?;
    let index = path.if_index.to_be(); // IP_UNICAST_IF expects DWORD in network byte order.
    let rc = unsafe {
        setsockopt(
            udp.as_raw_socket() as usize,
            IPPROTO_IP,
            IP_UNICAST_IF,
            &index as *const u32 as *const u8,
            std::mem::size_of::<u32>() as i32,
        )
    };
    if rc == SOCKET_ERROR {
        return Err(std::io::Error::last_os_error().into());
    }
    udp.connect(endpoint)?;
    Ok(udp)
}

/// Force an authenticated handshake so the VPS peer learns the new NAT
/// endpoint when traffic exits through a different adapter.
#[cfg(target_os = "windows")]
fn probe_path(tunn: &mut Tunn, udp: &UdpSocket, shutdown: &AtomicBool) -> Option<f64> {
    let mut send_buf = vec![0u8; WG_BUFFER_SIZE];
    let mut recv_buf = vec![0u8; WG_BUFFER_SIZE];
    let mut out_buf = vec![0u8; WG_BUFFER_SIZE];
    udp.set_nonblocking(false).ok()?;
    udp.set_read_timeout(Some(Duration::from_millis(200)))
        .ok()?;
    let start = Instant::now();
    let TunnResult::WriteToNetwork(init) = tunn.format_handshake_initiation(&mut send_buf, true)
    else {
        return None;
    };
    udp.send(init).ok()?;
    while start.elapsed() < PATH_PROBE_TIMEOUT {
        if shutdown.load(AtomicOrdering::Relaxed) {
            return None;
        }
        let n = match udp.recv(&mut recv_buf) {
            Ok(n) => n,
            Err(e)
                if matches!(
                    e.kind(),
                    std::io::ErrorKind::WouldBlock | std::io::ErrorKind::TimedOut
                ) =>
            {
                continue
            }
            Err(_) => return None,
        };
        let kind = recv_buf
            .get(..4)
            .and_then(|b| b.try_into().ok())
            .map(u32::from_le_bytes);
        let result = tunn.decapsulate(None, &recv_buf[..n], &mut out_buf);
        if matches!(result, TunnResult::Err(_)) {
            continue;
        }
        if let TunnResult::WriteToNetwork(response) = result {
            let _ = udp.send(response);
        }
        match kind {
            Some(2 | 4) => return Some(start.elapsed().as_secs_f64() * 1000.0),
            Some(3) => {
                if let TunnResult::WriteToNetwork(init) =
                    tunn.format_handshake_initiation(&mut send_buf, true)
                {
                    let _ = udp.send(init);
                }
            }
            _ => {}
        }
    }
    None
}

#[cfg(target_os = "windows")]
fn rank_internet_paths(
    tunn: &mut Tunn,
    endpoint: SocketAddr,
    shutdown: &AtomicBool,
) -> Result<Vec<PathCandidate>> {
    let mut paths = enumerate_internet_paths()?;
    for path in &mut paths {
        if let Ok(socket) = open_path_socket(path, endpoint) {
            path.latency_ms = probe_path(tunn, &socket, shutdown);
            path.available = path.latency_ms.is_some();
        }
    }
    paths.sort_by(|a, b| {
        b.available
            .cmp(&a.available)
            .then_with(|| {
                a.latency_ms
                    .partial_cmp(&b.latency_ms)
                    .unwrap_or(std::cmp::Ordering::Equal)
            })
            .then_with(|| a.metric.cmp(&b.metric))
    });
    Ok(paths)
}

#[cfg(target_os = "windows")]
fn merge_path_priority(
    previous: &[PathCandidate],
    mut current: Vec<PathCandidate>,
) -> Vec<PathCandidate> {
    for path in &mut current {
        if let Some(old) = previous
            .iter()
            .find(|old| old.if_index == path.if_index && old.local_ip == path.local_ip)
        {
            path.latency_ms = old.latency_ms;
            path.available = old.available;
        }
    }
    current.sort_by_key(|path| {
        previous
            .iter()
            .position(|old| old.if_index == path.if_index && old.local_ip == path.local_ip)
            .unwrap_or(previous.len() + path.metric as usize)
    });
    current
}

#[cfg(target_os = "windows")]
fn connect_ranked_path(
    tunn: &mut Tunn,
    endpoint: SocketAddr,
    previous: &[PathCandidate],
    current_if: Option<u32>,
    shutdown: &AtomicBool,
) -> Result<Option<(UdpSocket, PathCandidate, f64)>> {
    let mut paths = merge_path_priority(previous, enumerate_internet_paths()?);
    // During failover, try alternatives in original priority order and the
    // current connection last (it may have recovered while we switched).
    if let Some(active) = current_if {
        paths.sort_by_key(|path| path.if_index == active);
    }
    for mut path in paths {
        if shutdown.load(AtomicOrdering::Relaxed) {
            return Ok(None);
        }
        let Ok(socket) = open_path_socket(&path, endpoint) else {
            continue;
        };
        let Some(latency) = probe_path(tunn, &socket, shutdown) else {
            continue;
        };
        path.available = true;
        path.latency_ms = Some(latency);
        return Ok(Some((socket, path, latency)));
    }
    Ok(None)
}

#[cfg(target_os = "windows")]
fn path_statuses(paths: &[PathCandidate], active_if: u32) -> Vec<InternetPathStatus> {
    paths
        .iter()
        .enumerate()
        .map(|(index, path)| InternetPathStatus {
            name: path.name.clone(),
            local_ip: path.local_ip.to_string(),
            priority: index as u32 + 1,
            latency_ms: path.latency_ms,
            available: path.available,
            active: path.if_index == active_if,
        })
        .collect()
}

/// Load wintun.dll from several candidate paths:
/// - alongside the .exe (dev and bundle)
/// - bundle resources directory (Tauri)
/// - system PATH
#[cfg(target_os = "windows")]
fn load_wintun() -> Result<wintun::Wintun> {
    // 1. try next to the exe
    let exe_dir = std::env::current_exe()
        .map_err(|e| anyhow!("current_exe: {}", e))?
        .parent()
        .map(|p| p.to_path_buf())
        .unwrap_or_default();
    let candidates = [
        exe_dir.join("wintun.dll"),
        exe_dir.join("resources").join("wintun.dll"),
        std::path::PathBuf::from("wintun.dll"),
    ];
    for path in &candidates {
        if path.exists() {
            return unsafe { wintun::load_from_path(path) }
                .map_err(|e| anyhow!("wintun::load_from_path({:?}): {}", path, e));
        }
    }
    // 2. fallback: let the crate search PATH
    unsafe { wintun::load() }.map_err(|e| {
        anyhow!(
            "wintun::load (PATH): {}. Place wintun.dll next to the .exe",
            e
        )
    })
}

/// Measure direct latency (no tunnel) to Albion server — TCP connect ×10.
async fn measure_albion_latency_direct(shutdown: &AtomicBool) -> Option<f64> {
    let host = "gameinfo.albiononline.com:443";
    let mut samples = Vec::new();
    for _ in 0..10 {
        if shutdown.load(AtomicOrdering::Relaxed) {
            return None;
        }
        let start = Instant::now();
        match tokio::time::timeout(Duration::from_secs(2), tokio::net::TcpStream::connect(host))
            .await
        {
            Ok(Ok(_stream)) => {
                samples.push(start.elapsed().as_secs_f64() * 1000.0);
            }
            _ => {}
        }
        tokio::time::sleep(Duration::from_millis(80)).await;
    }
    if samples.is_empty() {
        return None;
    }
    Some(samples.iter().sum::<f64>() / samples.len() as f64)
}

/// Convert hex (64 chars) or base64 (44 chars) to 32 bytes.
fn parse_key(s: &str) -> Option<[u8; 32]> {
    let s = s.trim();
    if s.len() == 64 {
        // hex
        let mut out = [0u8; 32];
        for i in 0..32 {
            out[i] = u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).ok()?;
        }
        Some(out)
    } else if s.len() == 44 {
        // base64
        use base64::Engine;
        let decoded = base64::engine::general_purpose::STANDARD.decode(s).ok()?;
        if decoded.len() != 32 {
            return None;
        }
        let mut out = [0u8; 32];
        out.copy_from_slice(&decoded);
        Some(out)
    } else {
        None
    }
}

/// Generate a WireGuard keypair (private + public) for client configuration.
pub fn generate_keypair() -> (String, String) {
    use base64::Engine;
    use boringtun::x25519::{PublicKey, StaticSecret};
    use rand_core::OsRng;
    let secret = StaticSecret::random_from_rng(OsRng);
    let public = PublicKey::from(&secret);
    let priv_b64 = base64::engine::general_purpose::STANDARD.encode(secret.to_bytes());
    let pub_b64 = base64::engine::general_purpose::STANDARD.encode(public.to_bytes());
    (priv_b64, pub_b64)
}

