use wintun::Adapter;

#[cfg(target_os = "windows")]
use crate::albion_ips;

#[cfg(target_os = "windows")]
const TUNNEL_ADAPTER_NAME: &str = "Ziggs";
#[cfg(target_os = "windows")]
const TUNNEL_ADAPTER_TYPE: &str = "WireGuard";
#[cfg(target_os = "windows")]
const TUNNEL_IPV4_ADDR: Ipv4Addr = Ipv4Addr::new(10, 99, 0, 2);
#[cfg(target_os = "windows")]
const TUNNEL_IPV4_GW: Ipv4Addr = Ipv4Addr::new(10, 99, 0, 1);
#[cfg(target_os = "windows")]
const TUNNEL_NETMASK: Ipv4Addr = Ipv4Addr::new(255, 255, 255, 0);
#[cfg(target_os = "windows")]
const TUNNEL_MTU: usize = 1280;
#[cfg(target_os = "windows")]
const KEEPALIVE: Option<u16> = Some(25);
#[cfg(target_os = "windows")]
const PATH_HEALTH_INTERVAL: std::time::Duration = std::time::Duration::from_secs(5);
#[cfg(target_os = "windows")]
const PATH_PROBE_TIMEOUT: std::time::Duration = std::time::Duration::from_millis(1500);

#[cfg(target_os = "windows")]
const WG_BUFFER_SIZE: usize = 65535 + 32;

#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct TunnelConfig {
    /// WireGuard server endpoint (e.g. "203.0.113.10:51820")
    pub endpoint: String,
    /// Server public key (hex or base64)
    pub server_pubkey: String,
    /// Client private key (hex or base64) — generated by generate_keypair
    pub client_privkey: String,
    /// Enable tunnel on startup
    pub enabled: bool,
    /// Which Albion region this tunnel serves (e.g. "asia", "americas", "europe").
    /// Only that region's /24 game network is routed — so routing Asia doesn't
    /// disrupt an active Americas connection.
    pub albion_region: String,
}

impl Default for TunnelConfig {
    fn default() -> Self {
        Self {
            endpoint: String::new(),
            server_pubkey: String::new(),
            client_privkey: String::new(),
            enabled: false,
            albion_region: String::new(),
        }
    }
}

#[derive(Clone, Debug, Serialize, Deserialize)]
